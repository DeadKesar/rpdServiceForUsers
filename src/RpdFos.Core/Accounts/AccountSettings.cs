namespace RpdFos.Core.Accounts;

/// <summary>
/// Настройки служебных писем об учётной записи — раздел <c>Accounts</c> (этап 8, A6). Ссылка одноразовая: после
/// смены пароля прежние недействительны сразу, срок ограничивает только неиспользованную.
/// </summary>
public sealed class AccountSettings
{
    /// <summary>Сколько часов действует ссылка из письма «Забыли пароль?» (и ссылка подтверждения email, A8).</summary>
    public int ResetLinkHours { get; set; } = 24;

    /// <summary>
    /// Сколько часов действует ссылка приглашения. Дольше, чем у восстановления: приглашение приходит человеку, который
    /// о нём не просил, и может дождаться его возвращения из отпуска или с занятий.
    /// </summary>
    public int InviteLinkHours { get; set; } = 72;
}
