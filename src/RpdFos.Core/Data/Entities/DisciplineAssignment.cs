namespace RpdFos.Core.Data.Entities;

/// <summary>
/// Закрепление дисциплины за сотрудником (таблица discipline_assignments — дополнение модели данных, этап 7, A10; решение 5).
/// Методист закрепляет сотрудников за дисциплинами версии плана: закреплённый видит документы дисциплины (только для
/// чтения) и создаёт по ней РПД и ФОС, а у дисциплины с закреплениями остальные преподаватели документов не создают.
/// Закрепление не делится на РПД и ФОС и не переходит на новую версию плана — у неё другие строки <c>disciplines</c>.
/// Пара «дисциплина — сотрудник» уникальна. Строка не правится: закрепление появляется и снимается (строка удаляется), а
/// прошлое остаётся в журнале аудита.
/// </summary>
public class DisciplineAssignment
{
    public Guid Id { get; set; } = Guid.NewGuid();

    /// <summary>Дисциплина версии плана (строка <c>disciplines</c>, для которой создаётся документ).</summary>
    public Guid DisciplineId { get; set; }

    /// <summary>Закреплённый — запись справочника сотрудников.</summary>
    public Guid EmployeeId { get; set; }

    /// <summary>Кто закрепил — запись справочника (методист или администратор).</summary>
    public Guid AssignedBy { get; set; }

    public DateTimeOffset AssignedAt { get; set; }
}
