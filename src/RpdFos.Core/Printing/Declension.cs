        ["Зачёт с оценкой"] = ["зачёта с оценкой", "зачёту с оценкой", "зачёт с оценкой", "зачётом с оценкой", "зачёте с оценкой"],
        ["Курсовой проект"] = ["курсового проекта", "курсовому проекту", "курсовой проект", "курсовым проектом", "курсовом проекте"],
        ["Курсовая работа"] = ["курсовой работы", "курсовой работе", "курсовую работу", "курсовой работой", "курсовой работе"]
    };

    private static readonly string[] Order = [WordForms.Gen, WordForms.Dat, WordForms.Acc, WordForms.Ins, WordForms.Prep];

    /// <summary>Значение в нужной форме; null — формы нет в словаре (значение не из закрытого набора).</summary>
    public static string? Form(string value, string form)
    {
        if (form == WordForms.Nom) return value;
        var index = Array.IndexOf(Order, form);
        return index >= 0 && Forms.TryGetValue(value.Trim(), out var forms) ? forms[index] : null;
    }
}
