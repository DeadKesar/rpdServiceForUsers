using RpdFos.Core.DocumentTypes;

namespace RpdFos.Core.Printing;

/// <summary>
/// Формы слов для закрытых наборов значений плана: части плана, формы обучения, уровни образования,
/// квалификации, виды аттестации. Значения конечны и известны заранее, поэтому — словарь, без библиотек
/// морфологии (решение этапа 3). Не именительный падеж — со строчной буквы: значение стоит внутри фразы
/// («относится к обязательной части»).
/// </summary>
public static class Declension
{
    // Порядок форм: родительный, дательный, винительный, творительный, предложный.
    private static readonly Dictionary<string, string[]> Forms = new(StringComparer.OrdinalIgnoreCase)
    {
        ["Обязательная часть"] = ["обязательной части", "обязательной части", "обязательную часть", "обязательной частью", "обязательной части"],
        ["Часть, формируемая участниками образовательных отношений"] =
        [
            "части, формируемой участниками образовательных отношений", "части, формируемой участниками образовательных отношений",
            "часть, формируемую участниками образовательных отношений", "частью, формируемой участниками образовательных отношений",
            "части, формируемой участниками образовательных отношений"
        ],
        ["очная"] = ["очной", "очной", "очную", "очной", "очной"],
        ["заочная"] = ["заочной", "заочной", "заочную", "заочной", "заочной"],
        ["очно-заочная"] = ["очно-заочной", "очно-заочной", "очно-заочную", "очно-заочной", "очно-заочной"],
        ["Бакалавриат"] = ["бакалавриата", "бакалавриату", "бакалавриат", "бакалавриатом", "бакалавриате"],
        ["Магистратура"] = ["магистратуры", "магистратуре", "магистратуру", "магистратурой", "магистратуре"],
        ["Специалитет"] = ["специалитета", "специалитету", "специалитет", "специалитетом", "специалитете"],
        ["Аспирантура"] = ["аспирантуры", "аспирантуре", "аспирантуру", "аспирантурой", "аспирантуре"],
        ["бакалавр"] = ["бакалавра", "бакалавру", "бакалавра", "бакалавром", "бакалавре"],
        ["магистр"] = ["магистра", "магистру", "магистра", "магистром", "магистре"],
        ["специалист"] = ["специалиста", "специалисту", "специалиста", "специалистом", "специалисте"],
        ["Экзамен"] = ["экзамена", "экзамену", "экзамен", "экзаменом", "экзамене"],
