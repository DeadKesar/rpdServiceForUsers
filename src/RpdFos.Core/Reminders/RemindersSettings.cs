namespace RpdFos.Core.Reminders;

/// <summary>
/// Срок доработки и напоминания о нём — раздел <c>Reminders</c> конфигурации (этап 7, A6; FR-REV-09). Сроки — как в
/// проекте: 14 дней на доработке и предупреждение за 3 дня; других сроков нет (решение 6 автора).
/// </summary>
public sealed class RemindersSettings
{
    /// <summary>
    /// false — ежедневная задача не ставится (сервер без напоминаний; тесты, которые запускают её сами и не должны
    /// конкурировать с расписанием). На остальные уведомления это не влияет.
    /// </summary>
    public bool Enabled { get; set; } = true;

    /// <summary>
    /// Сколько дней документ может быть на доработке. По истечении срока заведующему кафедрой дисциплины и методистам
    /// уходит уведомление. Отсчёт — от последнего перехода документа в «На доработке».
    /// </summary>
    public int ReworkDays { get; set; } = 14;

    /// <summary>За сколько дней до срока автору уходит предупреждение «Срок доработки истекает».</summary>
    public int WarnDaysBefore { get; set; } = 3;
}
