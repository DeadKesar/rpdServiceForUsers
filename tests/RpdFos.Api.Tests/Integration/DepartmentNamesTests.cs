using RpdFos.Core.Import;
using Xunit;

namespace RpdFos.Api.Tests.Integration;

/// <summary>Нестрогое сравнение названий кафедр (этап 5.4, B6) — на вариантах из учебных планов корпуса.</summary>
public class DepartmentNamesTests
{
    [Theory]
    [InlineData("Автоматизированные системы обработки информации и управления", "Автоматизированные системы обработки информации и управление")]
    [InlineData("Социология, политология и нормативно-правовове регулирование промышленного развития", "Социология, политология и нормативно-правовое регулирование промышленного развития")]
    [InlineData("Социология, политология и нормативно-правовое регулированиепромышленного развития", "Социология, политология и нормативно-правовое регулирование промышленного развития")]
    [InlineData("Управвление по организации проектного обучения", "Управление по организации проектного обучения")]
    [InlineData("Технология космического машиностроения", "Технологии космического машиностроения")]
    [InlineData("Иностранный язык", "Иностранные языки")]
    [InlineData("Гидропневмоавтомактика и гидропривод", "Гидропневмоавтоматика и гидропривод")]
    [InlineData("ФИЗИЧЕСКОЕ  воспитание и спорт", "Физическое воспитание и спорт")]
    public void Variants_of_one_department_match(string a, string b) => Assert.True(DepartmentNames.Same(a, b));

    [Theory]
    [InlineData("Инженерная безопасность", "Информационная безопасность")]
    [InlineData("Технология машиностроения", "Технологическое проектирование")]
    [InlineData("Станки", "Физика")]
    public void Different_departments_do_not_match(string a, string b) => Assert.False(DepartmentNames.Same(a, b));
}
